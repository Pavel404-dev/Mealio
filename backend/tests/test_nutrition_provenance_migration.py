"""Genuine previous-head rows and schema; requires authorized disposable DB."""

import asyncio
import json
from uuid import uuid4

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy.exc import DBAPIError

from tests import test_ingredient_portion_migration as portion_migration
from tests.test_ingredient_identity_migration import identity_schema

migration_db = portion_migration.migration_db
PARENT = "b205c8d15a01"
REVISION = "c213a7e94b02"
CHECK = "ck_nutrition_values_source_pair"
FIELDS = {"source_name", "source_reference"}


@pytest.mark.parametrize("populated", [False, True])
async def test_previous_head_additive_roundtrip_and_current_model_parity(
    migration_db, populated
):
    db = migration_db
    await db.migrate("upgrade", PARENT)
    if populated:
        ids = await db.seed(["50", "999999.99"])
        await db.execute(
            "UPDATE nutrition_values SET calories=100.25,protein_g=1.23,carbs_g=4.50,fat_g=0.10 WHERE ingredient_id=:id",
            {"id": ids[0]},
        )
        # Preserve historical stored totals, even when they are stale; no repair.
        await db.execute(
            "UPDATE recipes SET total_calories=17.23,total_protein_g=2.34,total_carbs_g=3.45,total_fat_g=4.56"
        )
        # Legacy macro defaults really came from old DDL, not current ORM.
        await db.execute(
            "INSERT INTO ingredients(id,name) VALUES (:id,'Missing legacy nutrition')",
            {"id": uuid4()},
        )
    before = await db.state()
    identity = await identity_schema(db)
    assert not any(r[1] in FIELDS for r in before["columns"])
    await db.migrate("upgrade", REVISION)
    assert ScriptDirectory.from_config(db.config).get_heads() == [REVISION]
    after = await db.state()
    assert after["revision"] == [REVISION]
    assert await identity_schema(db) == identity
    for key in before:
        if key == "nutrition_values":
            assert [json.loads(row) for row in after[key]] == [
                {**json.loads(row), "source_name": None, "source_reference": None}
                for row in before[key]
            ]
        elif key == "columns":
            assert [
                r
                for r in after[key]
                if not (r[0] == "nutrition_values" and r[1] in FIELDS)
            ] == before[key]
        elif key == "constraints":
            assert [r for r in after[key] if r[1] != CHECK] == before[key]
            assert len([r for r in after[key] if r[1] == CHECK]) == 1
        elif key != "revision":
            assert after[key] == before[key]
    columns = (
        await db.execute(
            "SELECT column_name, character_maximum_length, is_nullable, column_default FROM information_schema.columns WHERE table_schema='public' AND table_name='nutrition_values' AND column_name IN ('source_name','source_reference') ORDER BY column_name"
        )
    ).all()
    assert columns == [
        ("source_name", 255, "YES", None),
        ("source_reference", 1000, "YES", None),
    ]
    await db.engine.dispose()
    await asyncio.to_thread(command.check, db.config)
    if populated:
        await db.execute(
            "UPDATE nutrition_values SET source_name='Synthetic label', source_reference='qa-pack:rev-1'"
        )
        await db.engine.dispose()
        assert (
            await db.execute(
                "SELECT source_name,source_reference FROM nutrition_values"
            )
        ).all() == [("Synthetic label", "qa-pack:rev-1")] * 2
        with pytest.raises(DBAPIError) as error:
            await db.execute("UPDATE nutrition_values SET source_name=NULL")
        assert error.value.orig.sqlstate == "23514"
        assert error.value.orig.__cause__.constraint_name == CHECK
        # Name alone and the unknown pair remain valid for direct SQL writers.
        await db.execute("UPDATE nutrition_values SET source_reference=NULL")
        await db.execute("UPDATE nutrition_values SET source_name=NULL")
        await db.execute(
            "UPDATE nutrition_values SET source_name='Synthetic final', source_reference='lost-on-downgrade'"
        )
    # Downgrade deliberately loses metadata and preserves every historical field,
    # numeric default, UUID/FK, missing row, stored total, constraint and index.
    await db.migrate("downgrade", PARENT)
    assert await db.state() == before
    assert await identity_schema(db) == identity
    await db.migrate("upgrade", REVISION)
    assert await db.state() == after
    await asyncio.to_thread(command.check, db.config)


@pytest.mark.parametrize(
    "drift", ["missing_source_column", "unrelated_column", "unrelated_index"]
)
async def test_current_head_check_keeps_reporting_column_and_unrelated_drift(
    migration_db, drift
):
    from alembic.util.exc import AutogenerateDiffsDetected

    db = migration_db
    await db.migrate("upgrade", "head")
    if drift == "missing_source_column":
        await db.execute("ALTER TABLE nutrition_values DROP COLUMN source_reference")
        expected = "source_reference"
    elif drift == "unrelated_column":
        await db.execute("ALTER TABLE ingredients ADD COLUMN unexpected_213 integer")
        expected = "unexpected_213"
    else:
        await db.execute("CREATE INDEX unexpected_213 ON ingredients(category)")
        expected = "unexpected_213"
    with pytest.raises(AutogenerateDiffsDetected, match=expected):
        await asyncio.to_thread(command.check, db.config)
